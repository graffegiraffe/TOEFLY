// Computes WCAG 2.2 contrast ratios for token pairs in css/theme.css and writes contrast-report.md.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const css = readFileSync(join(root, 'css/theme.css'), 'utf8');

function block(selector) {
  const start = css.indexOf(selector + ' {');
  const body = css.slice(start, css.indexOf('\n}', start));
  const vars = {};
  for (const m of body.matchAll(/--([\w-]+):\s*(#[0-9A-Fa-f]{6})/g)) vars[m[1]] = m[2];
  return vars;
}
const light = block(':root');
const dark = Object.assign({}, light, block('.dark'));

const lum = (hex) => {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

// [foreground token, background token, threshold, note]
const pairs = [
  ['ink', 'surface', 4.5], ['ink', 'canvas', 4.5], ['ink', 'surface-task', 4.5],
  ['ink-muted', 'surface', 4.5], ['ink-muted', 'canvas', 4.5], ['ink-subtle', 'surface', 4.5, 'placeholder only', 'accepted exception'],
  ['link', 'surface', 4.5], ['accent-on-soft', 'accent-soft', 4.5],
  ['success', 'surface', 4.5], ['warning', 'surface', 4.5], ['danger', 'surface', 4.5], ['info', 'surface', 4.5],
  ['ink', 'warning-soft', 4.5], ['ink', 'info-soft', 4.5], ['ink', 'danger-soft', 4.5], ['ink', 'success-soft', 4.5],
  ['#FFFFFF', 'primary', 4.5, 'primary button start'], ['#FFFFFF', '#0A8752', 4.5, 'primary button end'], ['#FFFFFF', 'danger-solid', 4.5],
  ['#FFFFFF', 'primary-hover', 4.5, 'button hover'],
  ['tag-reading-fg', 'tag-reading-bg', 4.5], ['tag-listening-fg', 'tag-listening-bg', 4.5], ['tag-writing-fg', 'tag-writing-bg', 4.5],
  ['tag-speaking-fg', 'tag-speaking-bg', 4.5], ['tag-vocabulary-fg', 'tag-vocabulary-bg', 4.5], ['tag-grammar-fg', 'tag-grammar-bg', 4.5],
  ['tag-resources-fg', 'tag-resources-bg', 4.5],
  ['neutral-500', 'surface', 3, 'checkbox outline (UI component)'], ['accent', 'surface', 3, 'rings, icons ≥20px with a text label', 'accepted exception'],
  ['sidebar-active-ink', 'glass-on-mesh', 4.5, 'active nav on glass, worst case approximated by surface'],
];
const val = (t, v) => (t.startsWith('#') ? t : t === 'glass-on-mesh' ? v.surface : v[t]);

let rows = '', fails = 0;
let exceptions = 0;
for (const [fg, bg, min, note, exc] of pairs) {
  const cells = [light, dark].map((v) => {
    const a = val(fg, v), b = val(bg, v);
    if (!a || !b) return { txt: 'n/a', ok: true };
    const r = ratio(a, b);
    return { txt: `${r.toFixed(2)}:1`, ok: r >= min };
  });
  const ok = cells.every((c) => c.ok);
  const status = ok ? 'pass' : exc ? 'exception' : 'FAIL';
  if (!ok && exc) exceptions++; else if (!ok) fails++;
  rows += `| \`${fg}\` / \`${bg}\` | ${cells[0].txt} | ${cells[1].txt} | ${min}:1 | ${status} | ${[note, exc].filter(Boolean).join('; ')} |\n`;
}

const md = `# Contrast report

Generated by \`scripts/contrast-report.mjs\` from \`css/theme.css\` (WCAG 2.2 relative luminance). Run: \`node design/prototype/scripts/contrast-report.mjs\`.

Thresholds: 4.5:1 for text, 3:1 for UI components and graphics. Dark-theme values with alpha (\`border\`, \`border-strong\`) are not computed here.

| Pair (text / background) | Light | Dark | Required | Result | Note |
|---|---|---|---|---|---|
${rows}
Pairs failing: ${fails}. Documented exceptions: ${exceptions}.
`;
writeFileSync(join(root, 'contrast-report.md'), md);
console.log(md);

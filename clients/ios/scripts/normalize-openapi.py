#!/usr/bin/env python3
"""Writes the OpenAPI documents the Swift clients are generated from.

swift-openapi-generator 1.14 skips a schema written as `oneOf: [X, {type: 'null'}]`, so properties such as
`WeekTask.taskType`, `Attempt.section` or `SequenceAnswer.fragmentIds` vanish from the generated types (and a
SEQUENCE answer then fails to decode). The service contracts are correct OpenAPI 3.1 and stay as they are; this
script copies each one into its ToeflyKit target and rewrites only that construct:

- a nullable property becomes a plain `$ref` (none of them is in `required`, so the Swift property is optional and
  `null` decodes as nil);
- a nullable array item becomes `type: [string, 'null']` (only string schemas occur there).

Usage (from anywhere):
  python3 clients/ios/scripts/normalize-openapi.py          rewrite the copies
  python3 clients/ios/scripts/normalize-openapi.py --check  fail if a copy is stale (run by `swift test`)
"""
import pathlib
import re
import sys

IOS = pathlib.Path(__file__).resolve().parent.parent
REPO = IOS.parent.parent
SOURCES = IOS / "Packages" / "ToeflyKit" / "Sources"

TARGETS = {
    "PlanningAPI": REPO / "services/planning-service/src/main/openapi/planning-service.yaml",
    "PracticeAPI": REPO / "services/practice-service/src/main/openapi/practice-service.yaml",
}

NULLABLE = re.compile(
    r"^(?P<indent> *)(?P<key>[A-Za-z]+):\n"
    r"(?P=indent)  oneOf:\n"
    r"(?P=indent)    - \{ \$ref: '(?P<ref>#/components/schemas/[A-Za-z]+)' \}\n"
    r"(?P=indent)    - \{ type: 'null' \}\n",
    re.MULTILINE,
)


def string_schemas(text: str) -> set[str]:
    return set(re.findall(r"^    ([A-Za-z]+):\n      type: string\n", text, re.MULTILINE))


def normalize(text: str) -> str:
    strings = string_schemas(text)

    def rewrite(match: re.Match) -> str:
        indent, key, ref = match["indent"], match["key"], match["ref"]
        if key == "items":
            name = ref.rsplit("/", 1)[-1]
            if name not in strings:
                raise SystemExit(f"nullable array item {ref} is not a string schema")
            return f"{indent}items: {{ type: [string, 'null'] }}\n"
        return f"{indent}{key}:\n{indent}  $ref: '{ref}'\n"

    result = NULLABLE.sub(rewrite, text)
    if "type: 'null' }" in result:
        raise SystemExit("a nullable oneOf in an unexpected shape is left; extend normalize-openapi.py")
    header = (
        "# Generated by clients/ios/scripts/normalize-openapi.py from the service contract; do not edit.\n"
        "# Nullable oneOf schemas are rewritten for swift-openapi-generator 1.14.\n"
    )
    return header + result


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for target, source in TARGETS.items():
        destination = SOURCES / target / "openapi.yaml"
        expected = normalize(source.read_text())
        current = destination.read_text() if destination.is_file() and not destination.is_symlink() else None
        if current == expected:
            continue
        if check:
            stale.append(str(destination.relative_to(REPO)))
        else:
            if destination.is_symlink():
                destination.unlink()
            destination.write_text(expected)
            print(f"wrote {destination.relative_to(REPO)}")
    if stale:
        print("Stale OpenAPI copies (run clients/ios/scripts/normalize-openapi.py): " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

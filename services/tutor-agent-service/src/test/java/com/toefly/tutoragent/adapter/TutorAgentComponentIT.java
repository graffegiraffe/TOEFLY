    static String chunk(String delta, String finish) {
        return "data: {\"id\":\"chatcmpl-1\",\"object\":\"chat.completion.chunk\",\"created\":1,\"model\":\"m\","
                + "\"choices\":[{\"index\":0,\"delta\":" + delta + ",\"finish_reason\":"
                + (finish == null ? "null" : "\"" + finish + "\"") + "}]}\n\n";
    }

    static com.github.tomakehurst.wiremock.client.ResponseDefinitionBuilder sse(String... chunks) {
        return aResponse()
                .withHeader("Content-Type", "text/event-stream")
                .withBody(String.join("", chunks)
                        + "data: {\"id\":\"chatcmpl-1\",\"object\":\"chat.completion.chunk\",\"created\":1,\"model\":\"m\","
                        + "\"choices\":[],\"usage\":{\"prompt_tokens\":50,\"completion_tokens\":10,\"total_tokens\":60}}\n\n"
                        + "data: [DONE]\n\n");
    }

    private void send(String topic, SpecificRecord event) throws Exception {
        UUID eventId = (UUID) event.get(event.getSchema().getField("eventId").pos());
        UUID userId = (UUID) event.get(event.getSchema().getField("userId").pos());
        EventPayloadSerializer.SerializedPayload payload = serializer.serialize(topic, event);
        Properties properties = new Properties();
        properties.put(ProducerConfig.BOOTSTRAP_SERVERS_CONFIG, kafka.getBootstrapServers());
        try (var producer = new KafkaProducer<>(properties, new StringSerializer(), new ByteArraySerializer())) {
            ProducerRecord<String, byte[]> record = new ProducerRecord<>(topic, userId.toString(), payload.bytes());
            record.headers().add(CloudEventHeaders.ID, eventId.toString().getBytes(StandardCharsets.UTF_8));
            record.headers().add("ce_type", topic.getBytes(StandardCharsets.UTF_8));
            producer.send(record).get();
        }
    }
